package org.meshtastic.core.network.radio

import org.meshtastic.core.ble.BleConnectionFactory
import org.meshtastic.core.ble.BleScanner
import org.meshtastic.core.ble.BluetoothRepository
import org.meshtastic.core.di.CoroutineDispatchers
import org.meshtastic.core.repository.RadioInterfaceService
import org.meshtastic.core.repository.RadioTransport

/** [BaseRadioTransportFactory] for the platforms that can open a raw TCP socket, which a browser cannot. */
abstract class NonWebRadioTransportFactory(
    scanner: BleScanner,
    bluetoothRepository: BluetoothRepository,
    connectionFactory: BleConnectionFactory,
    dispatchers: CoroutineDispatchers,
) : BaseRadioTransportFactory(scanner, bluetoothRepository, connectionFactory, dispatchers) {

    override fun createTcpTransport(service: RadioInterfaceService, rest: String): RadioTransport = TcpRadioTransport(
        callback = service,
        scope = service.serviceScope,
        dispatchers = dispatchers,
        address = rest,
    )
}
